#!/usr/bin/env node
// Generates the LCARS Obsidian theme in vault/.obsidian/themes/LCARS/ from lcars-design-system's
// resolved tokens. Colors and pills only: standard Obsidian layout, LCARS palette, pills for
// properties and tags. Also colors the Calendar plugin's dots by role. `node theme/build.mjs --check`
// exits 1 when a committed output is stale.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const tokens = require('lcars-design-system');
const dsVersion = require('lcars-design-system/package.json').version;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vault = join(root, 'vault');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const triplet = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(', ');

// One custom property per role; everything below reads roles, never a raw color (spec/guidelines.md).
function roleVars(palette) {
  return Object.entries(palette.roles).map(([role, hex]) => `  --lcars-${role}: ${hex};\n  --lcars-${role}-rgb: ${triplet(hex)};`).join('\n');
}

const others = Object.keys(tokens.palettes).filter((id) => id !== tokens.default);

const css = `/* LCARS theme for Obsidian, generated by theme/build.mjs in lcars-mainframe from
   lcars-design-system ${dsVersion}. Do not edit; change the design system or the generator.
   LCARS was designed by Michael Okuda and belongs to Paramount. Fan project, not affiliated. */

/* @settings
name: LCARS
id: lcars
settings:
  - id: lcars-palette
    title: Palette
    description: Which LCARS era supplies the colors.
    type: class-select
    allowEmpty: false
    default: lcars-palette-${tokens.default}
    options:
${Object.entries(tokens.palettes).map(([id, p]) => `      - label: ${p.name}\n        value: lcars-palette-${id}`).join('\n')}
*/

body {
${roleVars(tokens.palettes[tokens.default])}
  --lcars-h: 1.5em;
}
${others.map((id) => `body.lcars-palette-${id} {\n${roleVars(tokens.palettes[id])}\n}`).join('\n')}

/* LCARS is black in both modes; light mode keeps the same palette. */
.theme-dark, .theme-light {
  color-scheme: dark;
  --background-primary: #000;
  --background-primary-alt: #000;
  --background-secondary: #000;
  --background-secondary-alt: var(--lcars-unlit);
  --background-modifier-border: var(--lcars-unlit);
  --background-modifier-hover: rgba(var(--lcars-accent-rgb), 0.15);
  --background-modifier-active-hover: rgba(var(--lcars-accent-rgb), 0.25);
  --divider-color: var(--lcars-accent);
  --text-normal: var(--lcars-text);
  --text-muted: var(--lcars-muted);
  --text-faint: var(--lcars-unlit);
  --text-accent: var(--lcars-accent-4);
  --text-accent-hover: var(--lcars-value);
  --text-on-accent: var(--lcars-label-ink);
  --text-selection: rgba(var(--lcars-accent-rgb), 0.35);
  --text-error: var(--lcars-alert);
  --text-warning: var(--lcars-warning);
  --text-success: var(--lcars-ok);
  --interactive-accent: var(--lcars-accent);
  --interactive-accent-hover: var(--lcars-value);
  --color-accent: var(--lcars-accent);
  --link-color: var(--lcars-accent-4);
  --link-external-color: var(--lcars-accent-3);
  --link-unresolved-color: var(--lcars-muted);
  --checkbox-color: var(--lcars-accent);
  --checkbox-marker-color: var(--lcars-label-ink);
  --blockquote-border-color: var(--lcars-accent-2);
  --code-normal: var(--lcars-value);
  --h1-color: var(--lcars-accent);
  --h2-color: var(--lcars-value);
  --h3-color: var(--lcars-accent-2);
  --h4-color: var(--lcars-accent-3);
  --h5-color: var(--lcars-accent-4);
  --h6-color: var(--lcars-accent-5);
  --callout-default: var(--lcars-accent-4-rgb);
  --callout-info: var(--lcars-accent-4-rgb);
  --callout-todo: var(--lcars-accent-4-rgb);
  --callout-summary: var(--lcars-accent-4-rgb);
  --callout-important: var(--lcars-accent-rgb);
  --callout-tip: var(--lcars-ok-rgb);
  --callout-success: var(--lcars-ok-rgb);
  --callout-question: var(--lcars-accent-2-rgb);
  --callout-warning: var(--lcars-warning-rgb);
  --callout-fail: var(--lcars-alert-rgb);
  --callout-error: var(--lcars-alert-rgb);
  --callout-bug: var(--lcars-alert-rgb);
  --callout-example: var(--lcars-accent-3-rgb);
  --callout-quote: var(--lcars-muted-rgb);
  --tag-color: var(--lcars-label-ink);
  --tag-color-hover: var(--lcars-label-ink);
  --tag-background: var(--lcars-accent-2);
  --tag-background-hover: var(--lcars-accent-5);
  --tag-border-width: 0;
  --tag-radius: calc(var(--lcars-h) * 0.5);
  --tag-padding-x: calc(var(--lcars-h) * 0.5);
}

/* Headings: uppercase, condensed; h2 carries the LCARS rule with a rounded elbow. */
.markdown-rendered :is(h1, h2, h3, h4, h5, h6), .HyperMD-header {
  text-transform: uppercase;
  letter-spacing: 0.04em;
  font-family: Antonio, "Arial Narrow", "Roboto Condensed", var(--font-interface);
}
.markdown-rendered h2, .HyperMD-header-2 {
  border-bottom: 0.3em solid var(--lcars-accent);
  border-radius: 0 0 0 0.8em;
  padding-bottom: 0.1em;
}

/* Callouts: a lit bar on the left with a rounded elbow, the panel tinted by the callout's role. */
.callout {
  background-color: rgba(var(--callout-color), 0.12);
  border: 0;
  border-left: 0.6em solid rgb(var(--callout-color));
  border-radius: 1em 0 0 1em;
}
.callout-title, .callout-icon { color: rgb(var(--callout-color)); }
.callout-title-inner { text-transform: uppercase; letter-spacing: 0.04em; }

/* Tags: a pill without a value, label block between two half-circle caps (spec/pill.md). */
a.tag, .cm-hashtag {
  text-transform: uppercase;
  font-weight: 700;
  letter-spacing: 0.04em;
}

/* Properties: each one a pill readout. The key is the label block, the value sits on black, and
   every row's end cap closes at the right edge so the readouts line up as one panel. */
.metadata-container { --metadata-label-width: 13em; }
.metadata-property-key {
  background: var(--lcars-accent);
  color: var(--lcars-label-ink);
  border-radius: calc(var(--lcars-h) * 0.5) 0 0 calc(var(--lcars-h) * 0.5);
  padding-inline: calc(var(--lcars-h) * 0.5);
  --icon-color: var(--lcars-label-ink);
}
.metadata-property-key input { color: var(--lcars-label-ink); text-transform: uppercase; font-weight: 700; }
.metadata-property-value { color: var(--lcars-value); flex: 1 1 auto; }
.metadata-property-value::after {
  content: "";
  width: calc(var(--lcars-h) * 0.5);
  align-self: stretch;
  flex: none;
  margin-left: auto;
  background: var(--lcars-accent);
  border-radius: 0 calc(var(--lcars-h) * 0.5) calc(var(--lcars-h) * 0.5) 0;
}
.metadata-property:nth-child(5n + 2) { --lcars-accent: var(--lcars-accent-2); }
.metadata-property:nth-child(5n + 3) { --lcars-accent: var(--lcars-accent-3); }
.metadata-property:nth-child(5n + 4) { --lcars-accent: var(--lcars-accent-4); }
.metadata-property:nth-child(5n + 5) { --lcars-accent: var(--lcars-accent-5); }

/* Active tab and ribbon accents as lit blocks. */
.workspace-tab-header.is-active .workspace-tab-header-inner-title { color: var(--lcars-accent); }
.nav-file-title.is-active, .nav-folder-title.is-active {
  background: var(--lcars-accent);
  color: var(--lcars-label-ink);
  border-radius: calc(var(--lcars-h) * 0.5);
}
`;

const manifest = JSON.stringify({
  name: 'LCARS',
  version: pkg.version,
  minAppVersion: '1.6.0',
  author: 'lcars-mainframe',
}, null, 2) + '\n';

// The Calendar plugin stores dot colors as hex in its settings; give each source a role.
const calendarFile = '.obsidian/plugins/calendar-beta/data.json';
const calendar = JSON.parse(readFileSync(join(vault, calendarFile), 'utf8'));
const defaults = tokens.palettes[tokens.default].roles;
const dotRoles = { wordCount: 'value', tasks: 'warning', links: 'accent-4', backlinks: 'accent-3', zettels: 'accent-2' };
for (const [source, role] of Object.entries(dotRoles)) calendar.sourceSettings[source].color = defaults[role];

const outputs = {
  '.obsidian/themes/LCARS/theme.css': css,
  '.obsidian/themes/LCARS/manifest.json': manifest,
  [calendarFile]: JSON.stringify(calendar, null, 2) + '\n',
};
const check = process.argv.includes('--check');
let stale = 0;
for (const [name, body] of Object.entries(outputs)) {
  const file = join(vault, name);
  let current = null;
  try { current = readFileSync(file, 'utf8'); } catch {}
  if (current === body) continue;
  if (check) { console.error('stale: ' + file); stale++; }
  else { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, body); console.log('wrote ' + name); }
}
process.exit(stale ? 1 : 0);
