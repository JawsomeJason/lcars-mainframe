// The Calendar plugin stores dot colors as hex in its settings; give each source a role.
const calendarFile = '.obsidian/plugins/calendar-beta/data.json';
const calendar = JSON.parse(readFileSync(join(vault, calendarFile), 'utf8'));
const defaults = tokens.themes[DEFAULT].modes.dark;
const dotRoles = { wordCount: 'data', tasks: 'warning', links: 'accent', backlinks: 'block', zettels: 'stub' };
for (const [source, role] of Object.entries(dotRoles)) calendar.sourceSettings[source].color = defaults[role];

const outputs = {
  '.obsidian/themes/LCARS/theme.css': css,
  '.obsidian/themes/LCARS/manifest.json': manifest,
  '.obsidian/themes/LCARS/OFL-Antonio.txt': readFileSync(join(root, 'theme/fonts/OFL-Antonio.txt'), 'utf8'),
  '.obsidian/themes/LCARS/OFL-Lato.txt': readFileSync(join(root, 'theme/fonts/OFL-Lato.txt'), 'utf8'),
  [calendarFile]: JSON.stringify(calendar, null, 2) + '\n',
};
const check = process.argv.includes('--check');
let stale = 0;
for (const [name, body] of Object.entries(outputs)) {
  const file = join(vault, name);
  let current = null;
  try { current = readFileSync(file, 'utf8'); } catch {}
  if (current === body) continue;
  if (check) { console.error('stale: ' + file); stale++; }
  else { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, body); console.log('wrote ' + name); }
}
process.exit(stale ? 1 : 0);
